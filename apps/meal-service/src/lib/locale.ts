export function normalizeLocale(value: unknown): Locale {
  return value === "en" ? "en" : "vi";
}

export function readClientLocale(value: string | undefined | null = undefined): Locale {
  if (value) return normalizeLocale(value);
  if (typeof document === "undefined") return DEFAULT_LOCALE;
  const match = document.cookie.match(new RegExp(`(?:^|; )${LOCALE_COOKIE}=([^;]*)`));
  return normalizeLocale(match ? decodeURIComponent(match[1]) : null);
}

export function setLocaleCookie(locale: Locale) {
  document.cookie = `${LOCALE_COOKIE}=${locale}; path=/; max-age=31536000; samesite=lax`;
}

export function getTranslations(language: unknown) {
  return translations[normalizeLocale(language)];
}

export function localeLabel(locale: Locale) {
  return LANGUAGE_LABEL[locale];
}
